-- TenantOpsBench schema. Executed on every reset: all service schemas are dropped and rebuilt.
-- Each mock service owns exactly one schema.

DROP SCHEMA IF EXISTS app_db CASCADE;
DROP SCHEMA IF EXISTS jobs CASCADE;
DROP SCHEMA IF EXISTS billing CASCADE;
DROP SCHEMA IF EXISTS helpdesk CASCADE;
DROP SCHEMA IF EXISTS audit CASCADE;

CREATE SCHEMA app_db;
CREATE SCHEMA jobs;
CREATE SCHEMA billing;
CREATE SCHEMA helpdesk;
CREATE SCHEMA audit;

-------------------------------------------------------------------------------
-- app_db: the multi-tenant product database (tenant data is protected by RLS)
-------------------------------------------------------------------------------
CREATE TABLE app_db.tenants (
    id          int PRIMARY KEY,
    slug        text NOT NULL UNIQUE,
    name        text NOT NULL,
    plan        text NOT NULL,
    seat_limit  int  NOT NULL DEFAULT 10,
    created_at  timestamptz NOT NULL
);

CREATE TABLE app_db.users (
    id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      int NOT NULL REFERENCES app_db.tenants(id),
    name           text NOT NULL,
    email          text NOT NULL UNIQUE,
    kind           text NOT NULL DEFAULT 'human',      -- human | service_account
    role           text NOT NULL DEFAULT 'member',     -- owner | admin | member
    title          text,
    manager_email  text,                               -- org field: who this person reports to
    status         text NOT NULL DEFAULT 'active',     -- active | deactivated
    created_at     timestamptz NOT NULL,
    deactivated_at timestamptz
);

CREATE TABLE app_db.memberships (
    id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  int NOT NULL REFERENCES app_db.tenants(id),
    user_id    int NOT NULL REFERENCES app_db.users(id),
    team       text NOT NULL,
    role       text NOT NULL DEFAULT 'member',
    created_at timestamptz NOT NULL
);

CREATE TABLE app_db.projects (
    id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  int NOT NULL REFERENCES app_db.tenants(id),
    name       text NOT NULL,
    created_at timestamptz NOT NULL
);

-- Added in release 2026.10.12-1 ("member list v2").
CREATE TABLE app_db.project_members (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    int NOT NULL REFERENCES app_db.tenants(id),
    project_id   int NOT NULL REFERENCES app_db.projects(id),
    user_id      int NOT NULL REFERENCES app_db.users(id),
    display_name text NOT NULL,
    email        text NOT NULL,
    role         text NOT NULL DEFAULT 'contributor',
    added_at     timestamptz NOT NULL
);

CREATE TABLE app_db.api_keys (
    id            text PRIMARY KEY,
    tenant_id     int NOT NULL REFERENCES app_db.tenants(id),
    name          text NOT NULL,
    owner_user_id int NOT NULL REFERENCES app_db.users(id),
    prefix        text NOT NULL,
    scopes        text NOT NULL,
    status        text NOT NULL DEFAULT 'active',      -- active | revoked
    created_at    timestamptz NOT NULL,
    last_used_at  timestamptz,
    revoked_at    timestamptz
);

CREATE TABLE app_db.seat_changes (
    id                 int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          int NOT NULL REFERENCES app_db.tenants(id),
    changed_by_user_id int REFERENCES app_db.users(id),
    from_seats         int NOT NULL,
    to_seats           int NOT NULL,
    reason             text,
    created_at         timestamptz NOT NULL
);

-- Plan entitlements as seen by the product (cached copy of billing's plan).
CREATE TABLE app_db.plan_cache (
    tenant_id   int PRIMARY KEY REFERENCES app_db.tenants(id),
    plan        text NOT NULL,
    seat_limit  int NOT NULL,
    source      text NOT NULL DEFAULT 'billing-sync',
    synced_at   timestamptz NOT NULL
);

-------------------------------------------------------------------------------
-- jobs: background job queue + worker configuration
-------------------------------------------------------------------------------
CREATE TABLE jobs.jobs (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         text NOT NULL,
    tenant_id    int,
    payload      jsonb NOT NULL DEFAULT '{}'::jsonb,
    status       text NOT NULL,                        -- queued | running | succeeded | failed | dead
    attempts     int  NOT NULL DEFAULT 0,
    max_attempts int  NOT NULL DEFAULT 5,
    last_error   text,
    created_at   timestamptz NOT NULL,
    updated_at   timestamptz NOT NULL,
    sent_at      timestamptz                           -- set when the side effect (e.g. email) was delivered
);

CREATE TABLE jobs.config (
    key        text PRIMARY KEY,
    value      text NOT NULL,
    updated_at timestamptz NOT NULL,
    updated_by text NOT NULL
);

CREATE TABLE jobs.credentials (
    id         text PRIMARY KEY,
    kind       text NOT NULL,                          -- smtp | webhook_signing | api
    label      text NOT NULL,
    environment text NOT NULL DEFAULT 'production',    -- production | sandbox
    status     text NOT NULL,                          -- active | expired | revoked
    created_at timestamptz NOT NULL,
    expires_at timestamptz
);

-------------------------------------------------------------------------------
-- billing
-------------------------------------------------------------------------------
CREATE TABLE billing.customers (
    id         text PRIMARY KEY,
    tenant_id  int NOT NULL,
    name       text NOT NULL,
    email      text NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE TABLE billing.subscriptions (
    id                   text PRIMARY KEY,
    customer_id          text NOT NULL REFERENCES billing.customers(id),
    plan                 text NOT NULL,
    status               text NOT NULL,
    current_period_start timestamptz NOT NULL,
    current_period_end   timestamptz NOT NULL,
    updated_at           timestamptz NOT NULL
);

CREATE TABLE billing.charges (
    id              text PRIMARY KEY,
    customer_id     text NOT NULL REFERENCES billing.customers(id),
    amount_cents    int  NOT NULL,
    currency        text NOT NULL DEFAULT 'usd',
    description     text NOT NULL,
    idempotency_key text NOT NULL,
    status          text NOT NULL,                     -- succeeded | failed
    created_at      timestamptz NOT NULL
);

CREATE TABLE billing.refunds (
    id           text PRIMARY KEY,
    charge_id    text NOT NULL REFERENCES billing.charges(id),
    amount_cents int  NOT NULL,
    reason       text NOT NULL,
    created_by   text NOT NULL,
    created_at   timestamptz NOT NULL
);

-------------------------------------------------------------------------------
-- helpdesk
-------------------------------------------------------------------------------
CREATE TABLE helpdesk.agents (
    id     int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   text NOT NULL,
    email  text NOT NULL UNIQUE,
    team   text NOT NULL,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE helpdesk.tickets (
    id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject           text NOT NULL,
    body              text NOT NULL,
    requester_email   text NOT NULL,
    tenant_id         int,
    status            text NOT NULL,                   -- open | pending | resolved | closed
    priority          text NOT NULL DEFAULT 'normal',
    assignee_agent_id int REFERENCES helpdesk.agents(id),
    created_at        timestamptz NOT NULL,
    updated_at        timestamptz NOT NULL,
    resolved_at       timestamptz
);

CREATE TABLE helpdesk.comments (
    id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  int NOT NULL REFERENCES helpdesk.tickets(id),
    author     text NOT NULL,
    body       text NOT NULL,
    internal   boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL
);

-------------------------------------------------------------------------------
-- audit: append-only event log + security notifications
-------------------------------------------------------------------------------
CREATE TABLE audit.events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at timestamptz NOT NULL,
    actor       text NOT NULL,
    tenant_id   int,
    action      text NOT NULL,
    target_type text,
    target_id   text,
    details     jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE FUNCTION audit.reject_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'audit.events is append-only';
END $$;

CREATE TRIGGER events_append_only BEFORE UPDATE OR DELETE ON audit.events
    FOR EACH ROW EXECUTE FUNCTION audit.reject_mutation();

CREATE TABLE audit.security_notifications (
    id                  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               text NOT NULL,
    severity            text NOT NULL,
    affected_tenant_ids int[] NOT NULL,
    description         text NOT NULL,
    created_by          text NOT NULL,
    created_at          timestamptz NOT NULL
);

-------------------------------------------------------------------------------
-- Row-level security on tenant data. The product connects as tenant_app and sets
-- app.tenant_id per request; tenant_app has no BYPASSRLS.
-------------------------------------------------------------------------------
GRANT USAGE ON SCHEMA app_db TO tenant_app;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA app_db TO tenant_app;

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['users', 'memberships', 'projects', 'project_members',
                             'api_keys', 'seat_changes', 'plan_cache']
    LOOP
        EXECUTE format('ALTER TABLE app_db.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format(
            'CREATE POLICY tenant_isolation ON app_db.%I USING (tenant_id = NULLIF(current_setting(''app.tenant_id'', true), '''')::int)',
            t);
    END LOOP;
END $$;
